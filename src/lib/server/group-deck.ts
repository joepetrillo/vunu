/**
 * The next cards for you in a group's deck: the top eligible movies you
 * haven't answered, skipping `exclude` (cards already on screen or waiting
 * to save). No cursor or offset: rankings shift as people answer, so each
 * request asks for the current top.
 *
 * Eligible: enough votes, released in the US, on nobody in the group's seen
 * list, not watched by the group, and no Not seen of yours still counting.
 * Ranked: movies other members said Not seen to first, most of them first
 * ("finish what's started"), then best weighted rating, then movie ID. Your
 * preferences only pick the new movies: started ones reach you anyway, so
 * people with different preferences still reach matches.
 */
export async function dealCards(
  db: Db | Transaction,
  {
    groupId,
    userId,
    preferences,
    exclude = [],
    limit = DEAL_SIZE,
  }: {
    groupId: string;
    userId: string;
    preferences: Preferences;
    exclude?: readonly number[];
    limit?: number;
  }
): Promise<MovieCard[]> {
  // Others in the group still counting a Not seen, per movie.
  const started = db
    .select({
      movieId: notSeenMovies.movieId,
      confirmations: sql<number>`count(*)`.mapWith(Number).as("confirmations"),
    })
    .from(notSeenMovies)
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.userId, notSeenMovies.userId),
        eq(groupMembers.groupId, groupId)
      )
    )
    .where(and(ne(notSeenMovies.userId, userId), fresh()))
    .groupBy(notSeenMovies.movieId)
    .as("started");

  const fits = fitsPreferences(db, preferences);
  const rows = await db
    .select(cardColumns)
    .from(movies)
    .leftJoin(started, eq(started.movieId, movies.id))
    .where(
      and(
        dealable(),
        fits === undefined ? undefined : or(isNotNull(started.movieId), fits),
        notSeenInGroup(db, groupId, movies.id),
        notWatchedByGroup(db, groupId, movies.id),
        notExists(
          db
            .select({ one: sql`1` })
            .from(notSeenMovies)
            .where(
              and(
                eq(notSeenMovies.userId, userId),
                eq(notSeenMovies.movieId, movies.id),
                fresh()
              )
            )
        ),
        exclude.length === 0 ? undefined : notInArray(movies.id, [...exclude])
      )
    )
    .orderBy(
      desc(sql`coalesce(${started.confirmations}, 0)`),
      desc(weightedRating),
      asc(movies.id)
    )
    .limit(limit);
  return withGenres(db, rows);
}

/**
 * The group's matches: every current member has a Not seen still counting,
 * nobody in the group has seen it, and the group hasn't marked it watched.
 * Best weighted rating first; with preferences, the movies that fit them
 * come first. Derived from answers only, so preferences and catalog changes
 * never change what's a match.
 */
export async function listMatches(
  db: Db | Transaction,
  groupId: string,
  preferences: Preferences | null = null
): Promise<MovieCard[]> {
  const matched = matchedMovies(db, groupId).as("matched");
  const fits =
    preferences === null ? undefined : fitsPreferences(db, preferences);
  const rows = await db
    .select(cardColumns)
    .from(matched)
    .innerJoin(movies, eq(movies.id, matched.movieId))
    .orderBy(
      ...(fits === undefined ? [] : [desc(sql`coalesce(${fits}, false)`)]),
      desc(weightedRating),
      asc(movies.id)
    );
  return withGenres(db, rows);
}

/** How many matches the group has (the deck shows only the count). */
export async function countMatches(
  db: Db | Transaction,
  groupId: string
): Promise<number> {
  const [row] = await db
    .select({ count: sql<number>`count(*)`.mapWith(Number) })
    .from(matchedMovies(db, groupId).as("matched"));
  return row?.count ?? 0;
}

/**
 * Waiting on: movies at least two members said Not seen to (still
 * counting), that nobody in the group has seen or watched, and that some
 * members haven't answered yet, with those members' nicknames. Not matches.
 * Most answers first, then best rated.
 */
export async function listWaitingOn(
  db: Db | Transaction,
  groupId: string,
  viewerId: string
): Promise<{ movie: MovieCard; waitingOnYou: boolean; waitingOn: string[] }[]> {
  const memberCount = db
    .select({ n: sql`count(*)` })
    .from(groupMembers)
    .where(eq(groupMembers.groupId, groupId));
  const close = db
    .select({
      movieId: notSeenMovies.movieId,
      answers: sql<number>`count(*)`.mapWith(Number).as("answers"),
    })
    .from(notSeenMovies)
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.userId, notSeenMovies.userId),
        eq(groupMembers.groupId, groupId)
      )
    )
    .where(fresh())
    .groupBy(notSeenMovies.movieId)
    .having(
      and(
        sql`count(*) >= 2`,
        sql`count(*) < (${memberCount})`,
        notSeenInGroup(db, groupId, notSeenMovies.movieId),
        notWatchedByGroup(db, groupId, notSeenMovies.movieId)
      )
    )
    .as("close");
  const rows = await db
    .select(cardColumns)
    .from(close)
    .innerJoin(movies, eq(movies.id, close.movieId))
    .orderBy(desc(close.answers), desc(weightedRating), asc(movies.id))
    .limit(WAITING_ON_LIMIT);
  if (rows.length === 0) return [];

  // Who hasn't answered each: the members without a Not seen still counting.
  const missing = await db
    .select({
      movieId: movies.id,
      userId: groupMembers.userId,
      nickname: groupMembers.nickname,
    })
    .from(groupMembers)
    .innerJoin(
      movies,
      inArray(
        movies.id,
        rows.map((row) => row.id)
      )
    )
    .where(
      and(
        eq(groupMembers.groupId, groupId),
        notExists(
          db
            .select({ one: sql`1` })
            .from(notSeenMovies)
            .where(
              and(
                eq(notSeenMovies.userId, groupMembers.userId),
                eq(notSeenMovies.movieId, movies.id),
                fresh()
              )
            )
        )
      )
    )
    .orderBy(asc(groupMembers.nickname));
  const cards = await withGenres(db, rows);
  // The viewer is told apart ("Waiting on you") rather than by nickname,
  // which another member could share.
  return cards.map((movie) => {
    const members = missing.filter((row) => row.movieId === movie.id);
    return {
      movie,
      waitingOnYou: members.some((row) => row.userId === viewerId),
      waitingOn: members
        .filter((row) => row.userId !== viewerId)
        .map((row) => row.nickname),
    };
  });
}

/** The group's watched movies, most recently marked first. */
export async function listWatched(
  db: Db | Transaction,
  groupId: string
): Promise<MovieCard[]> {
  const rows = await db
    .select(cardColumns)
    .from(groupWatchedMovies)
    .innerJoin(movies, eq(movies.id, groupWatchedMovies.movieId))
    .where(eq(groupWatchedMovies.groupId, groupId))
    .orderBy(desc(groupWatchedMovies.createdAt), asc(movies.id));
  return withGenres(db, rows);
}

/** One movie as a card (an undone answer's movie, shown again). */
export async function getCard(
  db: Db | Transaction,
  movieId: number
): Promise<MovieCard | null> {
  const rows = await db
    .select(cardColumns)
    .from(movies)
    .where(eq(movies.id, movieId));
  const [card] = await withGenres(db, rows);
  return card ?? null;
}

