// Changes

interface Change {
  /** Generated by the browser, so a retried request carries the same ID. */
  actionId: string;
  /** The acting user, from the login session. */
  userId: string;
  /** The group whose deck or page the request came from. */
  groupId: string;
}

/**
 * Records an answer from a group's deck. It's a fact about the person, so it
 * counts in every group they're in. Seen puts the movie on their seen list
 * and withdraws their Not seen ("Actually, I've seen this"); Not seen counts
 * for NOT_SEEN_DAYS, and answering it again restarts that.
 */
export function answerMovie(
  db: Db,
  change: Change & { movieId: number; answer: "seen" | "not_seen" }
): Promise<DeckOutcome> {
  const { actionId, userId, groupId, movieId, answer } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: answer === "seen" ? "answer_seen" : "answer_not_seen",
    groupId,
    movieId,
  };
  return runDeckAction(db, action, async (tx) => {
    await lockUserInGroup(tx, userId, groupId);
    if (answer === "seen") {
      await confirmSeen(tx, { actionId, userId, movieId });
      await tx
        .delete(notSeenMovies)
        .where(
          and(
            eq(notSeenMovies.userId, userId),
            eq(notSeenMovies.movieId, movieId)
          )
        );
    } else {
      await tx
        .insert(notSeenMovies)
        .values({ userId, movieId, lastConfirmedByAction: actionId })
        .onConflictDoUpdate({
          target: [notSeenMovies.userId, notSeenMovies.movieId],
          set: { answeredAt: sql`now()`, lastConfirmedByAction: actionId },
        });
    }
    await bumpSeenVersion(tx, userId);
  });
}

/**
 * Undoes your latest answer from this group's deck that isn't undone yet;
 * repeated undos step back through them. Your answer to that movie before
 * it, from any group's deck, counts again (a Not seen with its original
 * time). Undoing a Seen removes the seen-list entry only if this answer is
 * still its latest confirmation (see withdrawSeen). Returns the undone
 * movie, so the screen can show it again; a retried undo returns the same.
 */
export async function undoLastAnswer(
  db: Db,
  change: Change
): Promise<{ outcome: DeckOutcome; movieId: number | null }> {
  const { actionId, userId, groupId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "answer_undo",
    groupId,
  };
  const outcome = await runDeckAction(db, action, async (tx) => {
    await lockUserInGroup(tx, userId, groupId);
    const [last] = await answerStack(tx, userId, groupId).limit(1);
    if (last?.movieId == null) throw new Refusal("nothing_to_undo");
    const { movieId } = last;

    await markUndone(tx, last.id, actionId);
    if (last.type === "answer_seen") {
      await withdrawSeen(tx, { actionId: last.id, userId, movieId });
    } else {
      await tx
        .delete(notSeenMovies)
        .where(
          and(
            eq(notSeenMovies.userId, userId),
            eq(notSeenMovies.movieId, movieId),
            eq(notSeenMovies.lastConfirmedByAction, last.id)
          )
        );
    }

    const [previous] = await tx
      .select({
        id: actions.id,
        type: actions.type,
        createdAt: actions.createdAt,
      })
      .from(actions)
      .where(
        and(
          eq(actions.userId, userId),
          eq(actions.movieId, movieId),
          inArray(actions.type, [...ANSWER_TYPES]),
          isNull(actions.undoneByActionId)
        )
      )
      .orderBy(desc(actions.createdAt), desc(actions.id))
      .limit(1);
    if (previous?.type === "answer_not_seen") {
      // Back to that answer, with its own time: it expires when it would
      // have. A newer Not seen already there (re-confirmed since) stays.
      await tx
        .insert(notSeenMovies)
        .values({
          userId,
          movieId,
          answeredAt: previous.createdAt,
          lastConfirmedByAction: previous.id,
        })
        .onConflictDoNothing();
    } else if (previous?.type === "answer_seen") {
      // Back to the state right after that Seen, seen-list entry included.
      await confirmSeen(tx, { actionId: previous.id, userId, movieId });
    }
    await bumpSeenVersion(tx, userId);
  });

  const [undone] = await db
    .select({ movieId: actions.movieId })
    .from(actions)
    .where(eq(actions.undoneByActionId, actionId))
    .limit(1);
  return { outcome, movieId: undone?.movieId ?? null };
}

/**
 * We watched this: the movie leaves the group's matches and deck for good
 * (until unmarked). A group record: nobody's seen list changes, because not
 * every member may have watched it. Already marked: nothing changes.
 */
export function markWatched(
  db: Db,
  change: Change & { movieId: number }
): Promise<DeckOutcome> {
  const { actionId, userId, groupId, movieId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "group_mark_watched",
    groupId,
    movieId,
  };
  return runDeckAction(db, action, async (tx) => {
    await lockGroupForMember(tx, groupId, userId);
    const marked = await tx
      .insert(groupWatchedMovies)
      .values({ groupId, movieId, markedBy: userId })
      .onConflictDoNothing()
      .returning({ movieId: groupWatchedMovies.movieId });
    if (marked.length > 0) await notifyGroupChanged(tx, groupId);
  });
}

/** Takes a movie off the group's watched list. Not on it: nothing changes. */
export function unmarkWatched(
  db: Db,
  change: Change & { movieId: number }
): Promise<DeckOutcome> {
  const { actionId, userId, groupId, movieId } = change;
  const action: Action = {
    id: actionId,
    userId,
    type: "group_unmark_watched",
    groupId,
    movieId,
  };
  return runDeckAction(db, action, async (tx) => {
    await lockGroupForMember(tx, groupId, userId);
    const removed = await tx
      .delete(groupWatchedMovies)
      .where(
        and(
          eq(groupWatchedMovies.groupId, groupId),
          eq(groupWatchedMovies.movieId, movieId)
        )
      )
      .returning({ movieId: groupWatchedMovies.movieId });
    if (removed.length > 0) await notifyGroupChanged(tx, groupId);
  });
}

