/** Whether you have an answer from this group's deck left to undo. */
export async function canUndo(
  db: Db | Transaction,
  userId: string,
  groupId: string
): Promise<boolean> {
  const [last] = await answerStack(db, userId, groupId).limit(1);
  return last !== undefined;
}

interface DeckRequest {
  groupId: string;
  userId: string;
  preferences: Preferences;
  /** Cards the browser holds (on screen or waiting to save): not dealt. */
  exclude: readonly number[];
}

/**
 * The deck's state for you, from one snapshot. Callers have already checked
 * that you're in the group.
 */
export function readDeckState(
  db: Db,
  request: DeckRequest
): Promise<DeckState> {
  return db.transaction((tx) => deckStateIn(tx, request), SNAPSHOT);
}

/**
 * The poll (spec section 5): a tiny "unchanged" when the fingerprint the
 * browser sends still matches, otherwise the deck's state, from one
 * snapshot. `ended` once you're no longer in the group.
 */
export function pollGroupDeck(
  db: Db,
  request: DeckRequest & { since: string }
): Promise<PollReply> {
  const { groupId, userId, since } = request;
  return db.transaction(async (tx) => {
    const member = await tx.query.groupMembers.findFirst({
      columns: { userId: true },
      where: { groupId, userId },
    });
    if (member === undefined) return { status: "ended" };
    if ((await fingerprintIn(tx, groupId)) === since) {
      return { status: "unchanged" };
    }
    return { status: "changed", state: await deckStateIn(tx, request) };
  }, SNAPSHOT);
}

// Every read in the transaction sees the database as of its first query, so
// the fingerprint and the state it describes always agree.
const SNAPSHOT = {
  isolationLevel: "repeatable read",
  accessMode: "read only",
} as const;

async function deckStateIn(
  tx: Transaction,
  request: DeckRequest
): Promise<DeckState> {
  const { groupId, userId } = request;
  const cards = await dealCards(tx, request);
  return {
    cards,
    matchCount: await countMatches(tx, groupId),
    canUndo: await canUndo(tx, userId, groupId),
    fingerprint: await fingerprintIn(tx, groupId),
    // Only worth reading when you've run out of cards.
    waitingOn: cards.length === 0 ? await waitingOnFor(tx, request) : null,
  };
}

// The members holding up your matches: those who haven't answered a movie
// you said Not seen to (still counting) that's still alive in the group.
async function waitingOnFor(
  tx: Transaction,
  { groupId, userId }: DeckRequest
): Promise<string[]> {
  const mine = notSeenMovies;
  const theirs = alias(notSeenMovies, "theirs");
  const rows = await tx
    .select({ nickname: groupMembers.nickname })
    .from(groupMembers)
    .where(
      and(
        eq(groupMembers.groupId, groupId),
        ne(groupMembers.userId, userId),
        exists(
          tx
            .select({ one: sql`1` })
            .from(mine)
            .where(
              and(
                eq(mine.userId, userId),
                fresh(mine.answeredAt),
                notSeenInGroup(tx, groupId, mine.movieId),
                notWatchedByGroup(tx, groupId, mine.movieId),
                notExists(
                  tx
                    .select({ one: sql`1` })
                    .from(theirs)
                    .where(
                      and(
                        eq(theirs.userId, groupMembers.userId),
                        eq(theirs.movieId, mine.movieId),
                        fresh(theirs.answeredAt)
                      )
                    )
                )
              )
            )
        )
      )
    )
    .orderBy(asc(groupMembers.nickname));
  return rows.map((row) => row.nickname);
}

// A short digest of the group's revision, each member's answer counter, and
// how many of the members' Not seen answers still count (spec section 5).
// Answers bump only the answering user's counter, so every group they're in
// notices without writing to any of them. A Not seen expires with no write at
// all, so the count is what notices that: it drops when one expires.
async function fingerprintIn(
  tx: Transaction,
  groupId: string
): Promise<string> {
  const [group] = await tx
    .select({ revision: groups.revision })
    .from(groups)
    .where(eq(groups.id, groupId));
  const [members] = await tx
    .select({
      versions: sql<
        string | null
      >`string_agg(${users.id} || ':' || ${users.seenVersion}::text, ',' order by ${users.id})`,
    })
    .from(groupMembers)
    .innerJoin(users, eq(users.id, groupMembers.userId))
    .where(eq(groupMembers.groupId, groupId));
  const [notSeen] = await tx
    .select({ count: sql<number>`count(*)`.mapWith(Number) })
    .from(notSeenMovies)
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.userId, notSeenMovies.userId),
        eq(groupMembers.groupId, groupId)
      )
    )
    .where(fresh());
  const source = `${String(group?.revision ?? "")}|${members?.versions ?? ""}|${String(notSeen?.count ?? 0)}`;
  return createHash("sha256").update(source).digest("base64url").slice(0, 16);
}

