// The group deck (stage 8, spec section 1): the only module that changes
// Not seen answers and a group's watched movies. There are no sessions: a
// group's matches are the movies every current member answered Not seen to
// in the last 2 weeks, that nobody in the group has seen, and that the group
// hasn't marked watched. Everything the deck shows is derived from those
// stored facts, never stored itself.
//
// Each answer or undo locks the user's row, so one person's answers (from
// any device or group) apply one at a time. We watched this locks the
// group's row, like membership changes. Callers pass inputs that already
// passed #lib/deck-fields.ts; this module checks permissions.

/** Movies with fewer TMDB votes are too obscure to deal. Revisit in stage 9. */
export const VOTE_COUNT_FLOOR = 200;
/** How many cards one request deals: the visible card plus a small queue. */
export const DEAL_SIZE = 6;
/** How long a Not seen counts: people watch movies elsewhere and never say. */
export const NOT_SEEN_DAYS = 14;
/** The most movies the Waiting on list shows. */
export const WAITING_ON_LIMIT = 10;

// A Bayesian (IMDb-style) weighted rating: every movie starts as if it had
// RATING_PRIOR_VOTES votes of RATING_PRIOR_MEAN, so a 9.0 from 250 votes
// doesn't jump ahead of an 8.4 from 30,000. Chosen by simulation (project
// files stage-8/explore/report.md).
const RATING_PRIOR_VOTES = 500;
const RATING_PRIOR_MEAN = 6.5;
const weightedRating = sql<number>`((${movies.voteCount} * coalesce(${movies.voteAverage}, 0) + ${sql.raw(String(RATING_PRIOR_VOTES * RATING_PRIOR_MEAN))}) / (${movies.voteCount} + ${sql.raw(String(RATING_PRIOR_VOTES))}))`;

// Whether a Not seen answer still counts. now() is the transaction's start,
// so every check in one snapshot uses the same moment.
function fresh(answeredAt: Column = notSeenMovies.answeredAt): SQL {
  return sql`${answeredAt} > now() - interval '${sql.raw(String(NOT_SEEN_DAYS))} days'`;
}

/**
 * Why a change was refused (nothing changed, nothing was logged):
 * - `not_found`: no such group, or you aren't in it. One answer for both,
 *   like groups.ts, so group IDs reveal nothing.
 * - `movie_not_found`: no such movie in the catalog.
 * - `nothing_to_undo`: no answer left on your undo stack for this group.
 */
export type DeckRefusal = "not_found" | "movie_not_found" | "nothing_to_undo";

export type DeckOutcome = ActionOutcome | DeckRefusal;

// Thrown inside a transaction to roll it back, action log entry included, so
// a retry after the situation changes runs normally (like groups.ts).
class Refusal extends Error {
  constructor(readonly reason: DeckRefusal) {
    super(reason);
  }
}

async function runDeckAction(
  db: Db,
  action: Action,
  apply: (tx: Transaction) => Promise<void>
): Promise<DeckOutcome> {
  try {
    return await runAction(db, action, apply);
  } catch (error) {
    if (error instanceof Refusal) return error.reason;
    // The log's movie_id has a foreign key, checked as the action is logged:
    // a movie not in the catalog fails there, before the change runs.
    if (
      error instanceof DrizzleQueryError &&
      error.cause instanceof DatabaseError &&
      error.cause.code === "23503" &&
      error.cause.constraint === "actions_movie_id_movies_id_fkey"
    ) {
      return "movie_not_found";
    }
    throw error;
  }
}

const ANSWER_TYPES = ["answer_seen", "answer_not_seen"] as const;

