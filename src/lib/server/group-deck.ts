// Helpers

const cardColumns = {
  id: movies.id,
  title: movies.title,
  year: sql<number | null>`extract(year from ${movies.releaseDate})::int`,
  runtime: movies.runtime,
  posterPath: movies.posterPath,
};

// Enough votes and released in the US: the movies the deck may deal at all.
function dealable(): SQL | undefined {
  return and(
    gte(movies.voteCount, VOTE_COUNT_FLOOR),
    isNotNull(movies.usReleaseDate),
    lte(movies.usReleaseDate, sql`current_date`)
  );
}

// Whether a movie fits the preferences, or undefined for no preferences. A
// missing runtime or year fails these comparisons, so such movies are left
// out only while that preference is set.
function fitsPreferences(
  db: Db | Transaction,
  preferences: Preferences
): SQL | undefined {
  if (!hasPreferences(preferences)) return undefined;
  const { maxRuntime, minYear, maxYear, genreIds, animation, ratings } =
    preferences;
  const withGenres = (ids: number[]) =>
    db
      .select({ id: movieGenres.movieId })
      .from(movieGenres)
      .where(inArray(movieGenres.genreId, ids));
  return and(
    maxRuntime === null ? undefined : lte(movies.runtime, maxRuntime),
    minYear === null
      ? undefined
      : gte(movies.releaseDate, `${String(minYear)}-01-01`),
    maxYear === null
      ? undefined
      : lt(movies.releaseDate, `${String(maxYear + 1)}-01-01`),
    genreIds.length === 0
      ? undefined
      : inArray(movies.id, withGenres(genreIds)),
    animation === "any"
      ? undefined
      : animation === "only"
        ? inArray(movies.id, withGenres([ANIMATION_GENRE_ID]))
        : notInArray(movies.id, withGenres([ANIMATION_GENRE_ID])),
    ratings.length === 0 ? undefined : hasRating(ratings)
  );
}

// TMDB's US certifications for each rating people can pick. NR ("Not rated")
// is everything else: TMDB's own NR, a missing rating, or anything unusual.
const CERTIFICATIONS: Record<Exclude<Rating, "NR">, string[]> = {
  G: ["G"],
  PG: ["PG"],
  "PG-13": ["PG-13"],
  R: ["R", "NC-17"],
};
const RATED = Object.values(CERTIFICATIONS).flat();

function hasRating(ratings: Rating[]): SQL | undefined {
  const certifications = ratings.flatMap((rating) =>
    rating === "NR" ? [] : CERTIFICATIONS[rating]
  );
  return or(
    certifications.length === 0
      ? undefined
      : inArray(movies.usCertification, certifications),
    ratings.includes("NR")
      ? or(
          isNull(movies.usCertification),
          notInArray(movies.usCertification, RATED)
        )
      : undefined
  );
}

// Nobody in the group has the movie on their seen list. A Seen answer always
// puts it there, so this covers Seen answers too.
function notSeenInGroup(
  db: Db | Transaction,
  groupId: string,
  movieId: Column
): SQL {
  return notExists(
    db
      .select({ one: sql`1` })
      .from(seenMovies)
      .innerJoin(
        groupMembers,
        and(
          eq(groupMembers.userId, seenMovies.userId),
          eq(groupMembers.groupId, groupId)
        )
      )
      .where(eq(seenMovies.movieId, movieId))
  );
}

function notWatchedByGroup(
  db: Db | Transaction,
  groupId: string,
  movieId: Column
): SQL {
  return notExists(
    db
      .select({ one: sql`1` })
      .from(groupWatchedMovies)
      .where(
        and(
          eq(groupWatchedMovies.groupId, groupId),
          eq(groupWatchedMovies.movieId, movieId)
        )
      )
  );
}

// The group's matches: movies with as many counting Not seen answers from
// members as the group has members, nobody's Seen, and not watched.
function matchedMovies(db: Db | Transaction, groupId: string) {
  return db
    .select({ movieId: notSeenMovies.movieId })
    .from(notSeenMovies)
    .innerJoin(
      groupMembers,
      and(
        eq(groupMembers.userId, notSeenMovies.userId),
        eq(groupMembers.groupId, groupId)
      )
    )
    .where(fresh())
    .groupBy(notSeenMovies.movieId)
    .having(
      and(
        sql`count(*) = (${db
          .select({ n: sql`count(*)` })
          .from(groupMembers)
          .where(eq(groupMembers.groupId, groupId))})`,
        notSeenInGroup(db, groupId, notSeenMovies.movieId),
        notWatchedByGroup(db, groupId, notSeenMovies.movieId)
      )
    );
}

// Your answers from this group's deck not undone yet, newest first: your
// undo stack there.
function answerStack(db: Db | Transaction, userId: string, groupId: string) {
  return db
    .select({ id: actions.id, type: actions.type, movieId: actions.movieId })
    .from(actions)
    .where(
      and(
        eq(actions.userId, userId),
        eq(actions.groupId, groupId),
        inArray(actions.type, [...ANSWER_TYPES]),
        isNull(actions.undoneByActionId)
      )
    )
    .orderBy(desc(actions.createdAt), desc(actions.id))
    .$dynamic();
}

async function withGenres(
  db: Db | Transaction,
  rows: Omit<MovieCard, "genres">[]
): Promise<MovieCard[]> {
  if (rows.length === 0) return [];
  const links = await db
    .select({ movieId: movieGenres.movieId, name: genres.name })
    .from(movieGenres)
    .innerJoin(genres, eq(genres.id, movieGenres.genreId))
    .where(
      inArray(
        movieGenres.movieId,
        rows.map((row) => row.id)
      )
    )
    .orderBy(asc(genres.name));
  return rows.map((row) => ({
    ...row,
    genres: links
      .filter((link) => link.movieId === row.id)
      .map((link) => link.name),
  }));
}

/**
 * The checks for answering and undoing: you're in the group. Locks your user
 * row, so your answers (from any device or group) apply one at a time and
 * your undo stack can't change under an undo.
 */
async function lockUserInGroup(
  tx: Transaction,
  userId: string,
  groupId: string
): Promise<void> {
  await tx
    .select({ id: users.id })
    .from(users)
    .where(eq(users.id, userId))
    .for("update");
  const member = await tx.query.groupMembers.findFirst({
    columns: { userId: true },
    where: { groupId, userId },
  });
  if (member === undefined) throw new Refusal("not_found");
}

/**
 * Locks the group's row, if the user is in the group. Group records queue
 * behind membership changes, which take the same lock (groups.ts).
 */
async function lockGroupForMember(
  tx: Transaction,
  groupId: string,
  userId: string
): Promise<void> {
  const [group] = await tx
    .select({ id: groups.id })
    .from(groups)
    .where(eq(groups.id, groupId))
    .for("update");
  const member =
    group === undefined
      ? undefined
      : await tx.query.groupMembers.findFirst({
          columns: { userId: true },
          where: { groupId, userId },
        });
  if (member === undefined) throw new Refusal("not_found");
}
